def plural(text: str) -> str:
    if text.endswith('y') and not text.endswith(('ay', 'ey', 'oy')):
        return text[:-1] + 'ies'
    return text if text.endswith('s') else text + 's'


def type_noun(java_type: str) -> str:
    return words(re.sub(r'(List)?DTO$', '', java_type))


def messages(ep: Endpoint, ctrl: Controller, list_type: str | None) -> tuple[str, str]:
    if f'{ctrl.name}.{ep.name}' in MESSAGES:
        return MESSAGES[f'{ctrl.name}.{ep.name}']
    head = re.match(r'[a-z]+', ep.name).group(0)
    gerund, past = VERBS.get(head, ('Loading', 'loaded'))
    rest = words(ep.name[len(head):]) if head in VERBS else words(ep.name)
    noun = rest or (plural(type_noun(list_type)) if ep.name == 'search' and list_type else words(ctrl.name))
    return f'{gerund} {noun} ...', f'{noun[:1].upper()}{noun[1:]} {past}.'


def slice_name(ep: Endpoint) -> str:
    base = ep.item
    if base in PRIMITIVES:
        return f'{ep.name}Result'
    stem = lower_first(re.sub(r'DTO$', '', base))
    return f'{stem}List' if ep.is_list else stem


def pick_types(ctrl: Controller) -> tuple[str | None, str | None]:
    if ctrl.name in STORE_TYPES:
        return STORE_TYPES[ctrl.name]
    json_eps = [e for e in ctrl.endpoints if not e.is_blob and e.item not in PRIMITIVES]
    singles = Counter(e.item for e in json_eps if not e.is_list)
    lists = Counter(e.item for e in json_eps if e.is_list)
    search = next((e for e in json_eps if e.name == 'search' and e.is_list), None)
    detail = singles.most_common(1)[0][0] if singles else None
    listed = search.item if search else (lists.most_common(1)[0][0] if lists else None)
    return detail, listed


def render_store(ctrl: Controller, models: dict[str, Model]) -> str:
    detail, listed = pick_types(ctrl)
    t, l = detail or 'never', listed or 'never'
    service = f'{ctrl.name}Api'
    store = f'{ctrl.name}ApiStore'
    needs: dict[str, set[str]] = {}
    rx = {'switchMap'}
    slices: dict[str, tuple[str, str]] = {}
    methods = []

    def need(java: str) -> None:
        for name in referenced_types(java):
            if name in models:
                needs.setdefault(models[name].package, set()).add(name)

    for name in filter(None, (detail, listed)):
        need(name)

    l_has_id = listed in models and any(f.name == 'id' for f in models[listed].fields + (
        models[models[listed].parent].fields if models[listed].parent in models else []))

    for ep in ctrl.endpoints:
        if ep.is_blob:
            continue
        for p in ep.params:
            need(p.java)
        started, succeeded = messages(ep, ctrl, listed)

        if ep.returns == detail:
            patch = '{ data }'
        elif ep.is_list and ep.item == listed:
            patch = '{ dataList: data }'
        elif ep.returns in ('Boolean', 'boolean') and ep.verb == 'delete' \
                and [p.name for p in ep.params] == ['id']:
            patch = None  # removal of the store's own entity, handled below
        elif ep.returns in ('Boolean', 'boolean'):
            patch = '{}'
        else:
            key = slice_name(ep)
            need(ep.returns)
            ts = return_ts(ep)
            slices[key] = (ts, '[]' if ep.is_list else 'null')
            patch = f'{{ {key}: data }}'

        criteria = ep.name == 'search' and len(ep.params) == 1 and ep.params[0].kind == 'Body'
        args = ', '.join(p.name for p in ep.params)
        call = f'api.{ep.name}({args})'
        if patch is None:
            remaining = ('\n                  dataList: store.dataList().filter((item) => item.id !== id),'
                         if l_has_id else '')
            next_ = (f'() =>\n                patchState(\n                  store,\n'
                     f'                  requestSucceeded({{ data: null,{remaining} }}, {succeeded!r}),\n                )')
        else:
            arg = '()' if patch == '{}' else '(data)'
            next_ = f'{arg} => patchState(store, requestSucceeded({patch}, {succeeded!r}))'

        pipe = (f'          patchState(store, requestStarted({started!r}));\n'
                f'          return {call}.pipe(\n'
                f'            tapResponse({{\n'
                f'              next: {next_},\n'
                f'              error: (error) => patchState(store, requestFailed(error)),\n'
                f'            }}),\n          );\n')

        if criteria:
            crit = ts_type(ep.params[0].java)
            rx.add('filter')
            methods.append(
                f'    /** Accepts a signal: re-searches whenever the criteria change (null = wait). */\n'
                f'    {ep.name}: rxMethod<{crit} | null>((criteria$) =>\n'
                f'      criteria$.pipe(\n'
                f'        filter((criteria): criteria is {crit} => criteria !== null),\n'
                f'        switchMap((criteria) => {{\n'
                + pipe.replace(f'api.{ep.name}({args})', f'api.{ep.name}(criteria)')
                + '        }),\n      ),\n    ),\n')
            continue

        flatten = 'switchMap' if ep.is_read else 'concatMap'
        rx.add(flatten)
        if not ep.params:
            methods.append(f'    {ep.name}: rxMethod<void>(\n      {flatten}(() => {{\n'
                           + pipe.replace('\n          ', '\n        ') + '      }),\n    ),\n')
        else:
            fields_ = '; '.join(f'{p.name}{"" if p.required else "?"}: {param_ts(p)}' for p in ep.params)
            methods.append(f'    {ep.name}: rxMethod<{{ {fields_} }}>(\n'
                           f'      {flatten}(({{ {args} }}) => {{\n'
                           + pipe.replace('\n          ', '\n        ') + '      }),\n    ),\n')

    state_type = f'AppState<{t}, {l}>'
    extra_type = ''.join(f'  {k}: {ts}{" | null" if init == "null" else ""};\n' for k, (ts, init) in slices.items())
    extra_init = ''.join(f'  {k}: {init},\n' for k, (ts, init) in slices.items())
    state_decl = (f'export type {store[:-5]}State = {state_type}' +
                  (f' & {{\n{extra_type}}};\n' if slices else ';\n'))
