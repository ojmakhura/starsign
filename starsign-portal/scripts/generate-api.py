def write(path: Path, content: str, written: list[Path]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    written.append(path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--api', type=Path, default=PORTAL.parent / 'starsign-api')
    parser.add_argument('--force-stores', action='store_true', help='overwrite existing store files')
    args = parser.parse_args()

    models = load_models(args.api)
    controllers = load_controllers(args.api)
    written: list[Path] = []

    for package, content in render_models(models).items():
        write(APP / 'models' / f'{package}.ts', content, written)
    write(APP / 'services' / 'http-params.ts', HTTP_PARAMS, written)
    skipped = []
    for ctrl in controllers:
        write(APP / 'services' / ctrl.package / f'{kebab(ctrl.name)}-api.ts', render_service(ctrl, models), written)
        store = APP / 'store' / ctrl.package / f'{kebab(ctrl.name)}-api.store.ts'
        if store.exists() and not args.force_stores:
            skipped.append(store)
        else:
            write(store, render_store(ctrl, models), written)

    subprocess.run(['npx', 'prettier', '--log-level', 'warn', '--write', *map(str, written)], cwd=PORTAL, check=True)
    print(f'{len(models)} models, {len(controllers)} services, '
          f'{len(controllers) - len(skipped)} stores written; {len(skipped)} existing stores kept.')


if __name__ == '__main__':
    main()
