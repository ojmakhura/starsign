GENERATED = 'Generated by scripts/generate-api.py from starsign-api. Do not edit by hand.'

# --------------------------------------------------------------------------- types

PRIMITIVES = {
    'String': 'string', 'char': 'string', 'Character': 'string', 'UUID': 'string',
    'Boolean': 'boolean', 'boolean': 'boolean',
    'Integer': 'number', 'int': 'number', 'Long': 'number', 'long': 'number',
    'Short': 'number', 'short': 'number', 'Double': 'number', 'double': 'number',
    'Float': 'number', 'float': 'number', 'BigDecimal': 'number', 'BigInteger': 'number',
    'LocalDateTime': 'string', 'LocalDate': 'string', 'LocalTime': 'string',
    'Instant': 'string', 'OffsetDateTime': 'string', 'ZonedDateTime': 'string', 'Date': 'string',
    'byte[]': 'string', 'Object': 'unknown',
}
COLLECTIONS = ('List', 'Set', 'Collection')
# Hand-written generic models the generated code imports: Spring Data's Page, serialised VIA_DTO.
GENERIC_MODELS = {'Page': 'page'}


def split_generic(java: str) -> tuple[str, str | None]:
    """'List<Foo>' -> ('List', 'Foo'); 'Foo' -> ('Foo', None)."""
    m = re.fullmatch(r'(\w+)\s*<\s*(.+)\s*>', java.strip())
    return (m.group(1), m.group(2)) if m else (java.strip(), None)


def ts_type(java: str) -> str:
    outer, inner = split_generic(java)
    if outer in COLLECTIONS:
        return f'{ts_type(inner or "Object")}[]'
    if outer == 'Map':
        if inner:
            value = inner.split(',', 1)[1]
            return f'Record<string, {ts_type(value)}>'
        return 'Record<string, unknown>'
    if inner and outer in GENERIC_MODELS:
        return f'{outer}<{ts_type(inner)}>'
    return PRIMITIVES.get(outer, outer)


def referenced_types(java: str) -> set[str]:
    return {t for t in re.findall(r'[A-Z]\w*', java) if t not in PRIMITIVES and t not in COLLECTIONS + ('Map',)}


def kebab(name: str) -> str:
    return re.sub(r'(?<!^)(?=[A-Z])', '-', name).lower()


def words(name: str) -> str:
    return re.sub(r'(?<!^)(?=[A-Z])', ' ', name).lower()


def lower_first(name: str) -> str:
    return name[:1].lower() + name[1:]


# --------------------------------------------------------------------------- models

@dataclass
class Field:
    name: str
    java: str
    nullable: bool
    doc: str | None


@dataclass
class Model:
    name: str
    package: str
    kind: str  # 'class' | 'enum'
    doc: str | None
    parent: str | None = None
    fields: list[Field] = field(default_factory=list)
    literals: list[tuple[str, str]] = field(default_factory=list)


def clean_doc(raw: str | None) -> str | None:
    if not raw:
        return None
    raw = raw.strip().removeprefix('/**').removesuffix('*/')
    lines = [re.sub(r'^\s*\*\s?', '', line).strip() for line in raw.splitlines()]
    text = ' '.join(line for line in lines if line and not line.startswith('@'))
    text = re.sub(r'TODO: Model Documentation for\s+[\w.]+', '', text)
    return re.sub(r'\s+', ' ', text).strip() or None


def parse_model(path: Path, package: str) -> Model | None:
    src = path.read_text()
    enum = re.search(r'(/\*\*(?:(?!\*/).)*\*/)?\s*public enum (\w+)', src, re.S)
    if enum:
        model = Model(enum.group(2), package, 'enum', clean_doc(enum.group(1)))
        body = src[enum.end():]
        model.literals = re.findall(r'^\s*([A-Z][A-Z0-9_]*)\("([^"]*)"\)\s*[,;]', body, re.M)
        return model
    cls = re.search(r'(/\*\*(?:(?!\*/).)*\*/)?\s*public (?:abstract )?class (\w+)\s*(?:extends (\w+))?', src, re.S)
    if not cls:
        return None
    model = Model(cls.group(2), package, 'class', clean_doc(cls.group(1)), cls.group(3))
    attrs = src[cls.end(): src.find('Constructor taking only required properties')]
    for m in re.finditer(
        r'(/\*\*(?:(?!\*/).)*\*/)\s*(@Nullable\s+)?protected ([\w<>,.?\[\] ]+?) (\w+);', attrs, re.S
    ):
        model.fields.append(Field(m.group(4), m.group(3), bool(m.group(2)), clean_doc(m.group(1))))
    return model


def load_models(api: Path) -> dict[str, Model]:
    models: dict[str, Model] = {}
    for path in sorted((api / 'common' / JAVA_ROOT).glob('*/*.java')):
        model = parse_model(path, path.parent.name)
        if model:
            models[model.name] = model
    return models


def doc_comment(doc: str | None, indent: str = '') -> str:
    return f'{indent}/** {doc} */\n' if doc else ''


def render_models(models: dict[str, Model]) -> dict[str, str]:
    by_package: dict[str, list[Model]] = {}
    for model in models.values():
        by_package.setdefault(model.package, []).append(model)

    files: dict[str, str] = {}
    for package, items in sorted(by_package.items()):
        imports: dict[str, set[str]] = {}
        body: list[str] = []
        for model in items:
            if model.kind == 'enum':
                body.append(doc_comment(model.doc) + f'export enum {model.name} {{\n'
                            + ''.join(f"  {name} = '{value}',\n" for name, value in model.literals) + '}\n')
                continue
            refs = {model.parent} if model.parent else set()
            lines = []
            for f in model.fields:
                refs |= referenced_types(f.java)
                ts = ts_type(f.java)
                lines.append(doc_comment(f.doc, '  ')
                             + (f'  {f.name}?: {ts} | null;\n' if f.nullable else f'  {f.name}: {ts};\n'))
            extends = f' extends {model.parent}' if model.parent else ''
            body.append(doc_comment(model.doc) + f'export interface {model.name}{extends} {{\n' + ''.join(lines) + '}\n')
            for ref in refs:
                if ref in models and models[ref].package != package:
                    imports.setdefault(models[ref].package, set()).add(ref)
        header = f'// {GENERATED}\n'
        header += ''.join(f"import {{ {', '.join(sorted(names))} }} from './{pkg}';\n"
                          for pkg, names in sorted(imports.items()))
        files[package] = header + ('\n' if imports else '\n') + '\n'.join(body)
    return files


# --------------------------------------------------------------------------- endpoints

@dataclass
class Param:
    kind: str  # Path | Body | Query | File
    name: str
    java: str
    required: bool


@dataclass
class Endpoint:
    name: str
    verb: str
    path: str
    returns: str
    nullable: bool
    params: list[Param]

    @property
    def outer(self) -> str:
        return split_generic(self.returns)[0]

    @property
    def is_list(self) -> bool:
        return self.outer in COLLECTIONS

    @property
    def item(self) -> str:
        return split_generic(self.returns)[1] if self.is_list else self.returns

    @property
    def is_blob(self) -> bool:
        return self.returns == 'Resource'

    @property
    def is_text(self) -> bool:
        return self.returns == 'String'

    @property
    def is_read(self) -> bool:
        return self.verb == 'get' or self.name in ('search', 'pagedSearch')


@dataclass
class Controller:
    name: str  # e.g. "Workflow"
    package: str
    base: str
    endpoints: list[Endpoint]


def strip_suffix(path: str, path_vars: list[str]) -> str:
    suffix = ''.join(f'/{v}/{{{v}}}' for v in path_vars)
    return path[: -len(suffix)] if suffix and path.endswith(suffix) else path


def parse_controller(path: Path) -> Controller:
    src = path.read_text()
    base = re.search(r'@RequestMapping\("([^"]*)"\)', src).group(1)
    endpoints = []
    for chunk in src[src.index('public interface'):].split(';'):
        method = re.search(r'public (@Nullable )?ResponseEntity<(.+)> (\w+)\((.*)\)\s*throws', chunk, re.S)
        if not method:
            continue
        mapping = re.search(r'@(Get|Post|Put|Patch|Delete)Mapping\(\s*(?:value = "([^"]*)")?', chunk)
        params = []
        raw = method.group(4).strip()
        for p in re.split(r',\s*(?=@)', raw) if raw else []:
            annotation = re.match(r'@(\w+)', p).group(1)
            required = re.search(r'required = (true|false)', p)
            tokens = re.sub(r'@\w+(\([^)]*\))?', '', p).split()
            java, var = ' '.join(tokens[:-1]), tokens[-1]
            named = re.search(r'name = "(\w+)"', p)
            kind = {'PathVariable': 'Path', 'RequestBody': 'Body'}.get(annotation, 'Query')
            if java == 'MultipartFile':
                kind = 'File'
            params.append(Param(kind, named.group(1) if named else var, java,
                                required.group(1) == 'true' if required else True))
        path_vars = [p.name for p in params if p.kind == 'Path']
        endpoints.append(Endpoint(method.group(3), mapping.group(1).lower(),
                                  strip_suffix(mapping.group(2) or '', path_vars),
                                  method.group(2), bool(method.group(1)), params))
    name = path.stem.removesuffix('Controller')
    return Controller(name, path.parent.name, base, endpoints)


def load_controllers(api: Path) -> list[Controller]:
    return [parse_controller(p) for p in sorted((api / 'webservice' / JAVA_ROOT).glob('*/*Controller.java'))]


# --------------------------------------------------------------------------- services

def param_ts(p: Param) -> str:
    return 'File' if p.kind == 'File' else ts_type(p.java)


def signature(params: list[Param]) -> str:
    out, seen_optional = [], False
    for i, p in enumerate(params):
        later_required = any(q.required for q in params[i + 1:])
        if not p.required and not later_required:
            out.append(f'{p.name}?: {param_ts(p)} | null')
        elif not p.required:
            out.append(f'{p.name}: {param_ts(p)} | null | undefined')
        else:
            out.append(f'{p.name}: {param_ts(p)}')
    return ', '.join(out)


def url_expr(ep: Endpoint) -> str:
    path = re.sub(r'\{(\w+)\}', r'${\1}', ep.path)
    return f'`${{this.path}}{path}`' if path else 'this.path'


def return_ts(ep: Endpoint) -> str:
    if ep.is_blob:
        return 'Blob'
    return ts_type(ep.returns)


def render_service(ctrl: Controller, models: dict[str, Model]) -> str:
    cls = f'{ctrl.name}Api'
    needs: dict[str, set[str]] = {}
    rx: set[str] = set()
    uses_params = False
    methods = []

    for ep in ctrl.endpoints:
        for t in referenced_types(ep.returns) | {t for p in ep.params for t in referenced_types(p.java)}:
            if t in models:
                needs.setdefault(models[t].package, set()).add(t)
            elif t in GENERIC_MODELS:
                needs.setdefault(GENERIC_MODELS[t], set()).add(t)
        path_params = [p for p in ep.params if p.kind == 'Path']
        query = [p for p in ep.params if p.kind == 'Query']
        body = next((p for p in ep.params if p.kind == 'Body'), None)
        files = [p for p in ep.params if p.kind == 'File']

        url = url_expr(ep)
        if ep.verb == 'get':
            methods.append(
                f'  {ep.name}Url({signature(path_params)}): string {{\n    return {url};\n  }}\n')
            url = f'this.{ep.name}Url({", ".join(p.name for p in path_params)})'

        options = []
        if query:
            uses_params = True
            options.append(f'params: toParams({{ {", ".join(p.name for p in query)} }})')
        if ep.is_blob:
            options.append("responseType: 'blob'")
        elif ep.is_text:
            options.append("responseType: 'text'")
        opts = f', {{ {", ".join(options)} }}' if options else ''

        generic = '' if (ep.is_blob or ep.is_text) else f'<{return_ts(ep)}>'
        prep = ''
        if files:
            prep = '    const form = new FormData();\n'
            prep += ''.join(f'    form.append(\'{f.name}\', {f.name}, {f.name}.name);\n' for f in files)
            if body:
                prep += (f"    form.append('{body.name}', new Blob([JSON.stringify({body.name})], "
                         "{ type: 'application/json' }));\n")
            payload = 'form'
        else:
            payload = body.name if body else '{}'

        call = (f'this.http.{ep.verb}{generic}({url}{opts})' if ep.verb in ('get', 'delete')
                else f'this.http.{ep.verb}{generic}({url}, {payload}{opts})')
        if ep.is_list:
            rx.add('map')
            call += '\n      .pipe(map((list) => list ?? []))'
            note = '  /** An empty list may come back with no body; it is normalised to []. */\n'
        else:
            note = ''
        methods.append(f'{note}  {ep.name}({signature(ep.params)}): Observable<{return_ts(ep)}> {{\n'
                       f'{prep}    return {call};\n  }}\n')

    imports = ["import { HttpClient } from '@angular/common/http';",
               "import { inject, Service } from '@angular/core';"]
    imports += [f"import {{ {', '.join(sorted(n))} }} from '@models/{pkg}';" for pkg, n in sorted(needs.items())]
    imports.append(f"import {{ {', '.join(['Observable', *sorted(rx)])} }} from 'rxjs';")
    if uses_params:
        imports.append("import { toParams } from '../http-params';")
    return (f'// {GENERATED}\n' + '\n'.join(imports) + '\n\n'
            f'/** {ctrl.base} */\n@Service()\nexport class {cls} {{\n'
            f"  protected path = '{ctrl.base}';\n  private http = inject(HttpClient);\n\n"
            + '\n'.join(methods) + '}\n')


HTTP_PARAMS = f"""// {GENERATED}
import {{ HttpParams }} from '@angular/common/http';

type ParamValue = string | number | boolean | null | undefined | Record<string, unknown>;

/** Query parameters from an object, skipping null/undefined; objects are flattened one level. */
export function toParams(values: Record<string, ParamValue>): HttpParams {{
  let params = new HttpParams();
  for (const [key, value] of Object.entries(values)) {{
    if (value === null || value === undefined) {{
      continue;
    }}
    if (typeof value === 'object') {{
      for (const [inner, innerValue] of Object.entries(value)) {{
        if (innerValue !== null && innerValue !== undefined) {{
          params = params.set(inner, String(innerValue));
        }}
      }}
      continue;
    }}
    params = params.set(key, String(value));
  }}
  return params;
}}
"""

