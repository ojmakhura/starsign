#!/usr/bin/env python3
"""
Generates the portal's API layer from the AndroMDA output in ../starsign-api:

  starsign-api/common      value objects + enumerations -> src/app/models/<package>.ts
  starsign-api/webservice  *Controller interfaces       -> src/app/services/<package>/<name>-api.ts
                                                         -> src/app/store/<package>/<name>-api.store.ts

Models and services are fully generated and overwritten on every run; do not edit them.
Stores are scaffolds: they are written only when the file does not exist yet (or with
--force-stores), so hand-written additions to a store survive regeneration.

Paths: the generated Spring mappings repeat every path variable as a suffix
("/{id}/cancel/id/{id}"). That suffix is a cartridge artefact, not part of the API
contract, so it is stripped ("/{id}/cancel").

Usage:  python3 scripts/generate-api.py [--api ../starsign-api] [--force-stores]
"""
